"""Radar-seeded sparse latent diffusion for the frozen Minkowski LiDAR decoder.

All sparse sites are derived from the radar/fault-area gate. Clean LiDAR may
supervise their latent features and occupancy, but never creates query sites.
"""

from __future__ import annotations

import math

import torch
from torch import nn
from torch.nn import functional as F

from models.lidar_minkowski_ae import SparseVoxelAutoencoder, _inside, _keys
from models.radar_lidar_stage2.sparse_geometry import GRID

try:
    import MinkowskiEngine as ME
except ImportError as exc:
    ME = None
    _ME_ERROR = exc


LATENT_CHANNELS = 64
RADAR_CHANNELS = 768


def voxelize_bxyz(points: torch.Tensor, batch_ids: torch.Tensor) -> torch.Tensor:
    """Occupied Stage-II voxel coordinates, sorted and unique in BXYZ order."""
    if points.ndim != 2 or points.shape[1] != 3 or batch_ids.shape != (len(points),):
        raise ValueError("Expected XYZ points and one batch ID per point")
    minimum = points.new_tensor(GRID.minimum_xyz)
    maximum = points.new_tensor(GRID.maximum_xyz)
    size = points.new_tensor(GRID.voxel_xyz)
    valid = ((points >= minimum) & (points < maximum)).all(1)
    cells = torch.floor((points[valid] - minimum) / size).int()
    return torch.unique(torch.cat((batch_ids[valid, None].int(), cells), 1), dim=0)


def radar_parent_sites(fine_zyx: list[torch.Tensor], device: torch.device
                       ) -> tuple[torch.Tensor, torch.Tensor]:
    """Fine gate and its stride-2 parents; no clean or faulty sites are added."""
    fine_parts = []
    for frame, local in enumerate(fine_zyx):
        if local.ndim != 2 or local.shape[1] != 3:
            raise ValueError("Radar gate must supply [N,3] ZYX cells per frame")
        xyz = local[:, [2, 1, 0]].int().to(device)
        batch = torch.full((len(xyz), 1), frame, dtype=torch.int32, device=device)
        fine_parts.append(torch.cat((batch, xyz), 1))
    fine = torch.cat(fine_parts)
    parents = fine.clone()
    parents[:, 1:] = torch.div(parents[:, 1:], 2, rounding_mode="floor") * 2
    return fine, torch.unique(parents, dim=0)


def gather_codes(source_coords: torch.Tensor, source_features: torch.Tensor,
                 query_coords: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
    """Join sparse BXYZ features; absent clean blocks have a zero target code."""
    if source_features.ndim != 2 or len(source_features) != len(source_coords):
        raise ValueError("Source coordinates and features differ")
    output = source_features.new_zeros((len(query_coords), source_features.shape[1]))
    found = torch.zeros(len(query_coords), dtype=torch.bool, device=query_coords.device)
    if not len(source_coords) or not len(query_coords):
        return output, found
    keys = _keys(source_coords)
    order = torch.argsort(keys)
    keys = keys[order]
    query = _keys(query_coords)
    positions = torch.searchsorted(keys, query)
    safe = positions.clamp(max=len(keys) - 1)
    found = (positions < len(keys)) & (keys[safe] == query)
    output[found] = source_features[order[safe[found]]]
    return output, found


def gather_logits(candidate_coords: torch.Tensor, logits: torch.Tensor,
                  gate_coords: torch.Tensor) -> torch.Tensor:
    """Every radar gate voxel must be generated by its stride-2 parent."""
    if len(candidate_coords) != len(logits):
        raise ValueError("Decoder coordinates and logits differ")
    if not len(gate_coords):
        return logits[:0]
    if not len(candidate_coords):
        raise RuntimeError("Frozen decoder did not generate any radar gate sites")
    keys = _keys(candidate_coords)
    order = torch.argsort(keys)
    keys = keys[order]
    positions = torch.searchsorted(keys, _keys(gate_coords))
    safe = positions.clamp(max=max(len(keys) - 1, 0))
    if not bool(((positions < len(keys)) &
                 (keys[safe] == _keys(gate_coords))).all()):
        raise RuntimeError("Frozen decoder did not generate every radar gate site")
    return logits[order[safe]]


def radar_anchor_features(parents: torch.Tensor,
                          anchors: list[tuple[torch.Tensor, torch.Tensor]],
                          *, chunk: int = 4096) -> torch.Tensor:
    """Interpolate three measured PointNet++ anchor features per parent site."""
    if not anchors:
        raise ValueError("At least one radar frame is required")
    width = anchors[0][1].shape[1]
    output = anchors[0][1].new_zeros((len(parents), width))
    origin = output.new_tensor(GRID.minimum_xyz)
    voxel = output.new_tensor(GRID.voxel_xyz)
    for batch, (xyz, features) in enumerate(anchors):
        if xyz.shape != (len(features), 3) or features.ndim != 2 or features.shape[1] != width:
            raise ValueError("Invalid PointNet++ anchor coordinates/features")
        selected = torch.where(parents[:, 0] == batch)[0]
        if not len(selected) or not len(xyz):
            continue
        k = min(3, len(xyz))
        for section in selected.split(chunk):
            # section is a contiguous slice of selected indices, not a grid cap.
            query = origin + (parents[section, 1:].to(output.dtype) + 1) * voxel
            distances, nearest = torch.cdist(query, xyz).topk(k, largest=False)
            weights = distances.clamp_min(0.05).reciprocal()
            weights = weights / weights.sum(1, keepdim=True)
            output[section] = (features[nearest] * weights[..., None]).sum(1)
    return output


def _replace(x, features):
    return ME.SparseTensor(features, coordinate_map_key=x.coordinate_map_key,
                           coordinate_manager=x.coordinate_manager)


class SparseLatentDenoiser(nn.Module):
    """One-level sparse U-Net over externally selected stride-2 sites."""

    def __init__(self, radar_channels: int = RADAR_CHANNELS):
        super().__init__()
        if ME is None:
            raise RuntimeError("MinkowskiEngine is required") from _ME_ERROR
        self.radar_channels = radar_channels
        self.radar_adapter = nn.Sequential(nn.LayerNorm(radar_channels),
                                           nn.Linear(radar_channels, 64), nn.SiLU())
        self.input = nn.Linear(64 * 3 + 1 + 3 + 16, 96)
        self.stem = ME.MinkowskiConvolution(96, 96, kernel_size=3, dimension=3)
        self.down = ME.MinkowskiConvolution(96, 128, kernel_size=2,
                                           stride=2, dimension=3)
        self.middle = ME.MinkowskiConvolution(128, 128, kernel_size=3, dimension=3)
        self.up = ME.MinkowskiConvolutionTranspose(128, 96, kernel_size=2,
                                                   stride=2, dimension=3)
        self.refine = ME.MinkowskiConvolution(96, 96, kernel_size=3, dimension=3)
        self.norm0 = nn.LayerNorm(96)
        self.norm1 = nn.LayerNorm(128)
        self.norm2 = nn.LayerNorm(96)
        self.head = nn.Linear(96, LATENT_CHANNELS)

    def forward(self, parents: torch.Tensor, noisy: torch.Tensor,
                faulty: torch.Tensor, radar: torch.Tensor,
                faulty_present: torch.Tensor, timestep: torch.Tensor) -> torch.Tensor:
        n = len(parents)
        if (parents.shape != (n, 4) or noisy.shape != (n, 64) or
                faulty.shape != (n, 64) or radar.shape != (n, self.radar_channels) or
                faulty_present.shape != (n,) or timestep.ndim != 1):
            raise ValueError("Sparse diffusion input dimensions differ")
        if not n:
            return noisy
        batch = parents[:, 0].long()
        if int(batch.max()) >= len(timestep):
            raise ValueError("Timestep batch dimension differs")
        phase = timestep[batch].to(noisy.dtype) / 999.0
        frequencies = 2.0 ** torch.arange(8, device=noisy.device, dtype=noisy.dtype)
        angles = phase[:, None] * frequencies[None] * math.pi
        time = torch.cat((angles.sin(), angles.cos()), 1)
        position = ((parents[:, 1:].to(noisy.dtype) + 1) /
                    noisy.new_tensor(GRID.shape_zyx[::-1]) * 2 - 1)
        features = torch.cat((noisy, faulty, self.radar_adapter(radar),
                              faulty_present[:, None].to(noisy.dtype),
                              position, time), 1)
        x = ME.SparseTensor(F.silu(self.input(features)),
                            coordinates=parents.int().contiguous(),
                            tensor_stride=(2, 2, 2))
        stem = self.stem(x)
        stem = _replace(stem, F.silu(self.norm0(stem.F)))
        hidden = self.down(stem)
        hidden = _replace(hidden, F.silu(self.norm1(hidden.F)))
        hidden = self.middle(hidden)
        hidden = _replace(hidden, F.silu(self.norm1(hidden.F)))
        raised = self.up(hidden, stem)
        if not torch.equal(raised.C, stem.C):
            aligned, found = gather_codes(raised.C, raised.F, stem.C)
            if not bool(found.all()):
                raise RuntimeError("Sparse U-Net lost radar-selected latent sites")
            raised = _replace(stem, aligned)
        raised = _replace(stem, F.silu(self.norm2(raised.F + stem.F)))
        refined = self.refine(raised)
        if not torch.equal(refined.C, stem.C):
            raise RuntimeError("Sparse refinement changed the radar query sites")
        output = self.head(F.silu(self.norm2(refined.F + raised.F)))
        if torch.equal(refined.C, parents):
            return output
        aligned, found = gather_codes(refined.C, output, parents)
        if not bool(found.all()):
            raise RuntimeError("Sparse denoiser omitted radar-selected parents")
        return aligned


def decode_codes(autoencoder: SparseVoxelAutoencoder, parents: torch.Tensor,
                 codes: torch.Tensor):
    """Run the frozen clean-LiDAR decoder on radar-generated coarse sites."""
    if ME is None:
        raise RuntimeError("MinkowskiEngine is required") from _ME_ERROR
    if codes.shape != (len(parents), LATENT_CHANNELS) or not bool(_inside(parents).all()):
        raise ValueError("Invalid stride-2 latent query sites or features")
    latent = ME.SparseTensor(features=codes, coordinates=parents.int(),
                             tensor_stride=(2, 2, 2))
    return autoencoder.decode(latent, fine_targets=None)
